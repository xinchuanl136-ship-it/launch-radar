// Launch Radar's value model: one sealed snapshot in, one ranked board out.
//
// The board ranks protocols that record no token, by the implied value a token
// might carry if the protocol's record stayed as it is. The model is deliberately
// small and stated in full, here and on the dashboard, so a reader can check every
// number on the board against the snapshot:
//
//   base      = tvl_usd x 0.30
//   momentum  = 1 + clamp(change_7d, -40, 100) / 100
//   tenure    = 0.70 + 0.30 x min(age_days, 730) / 730   (age unknown: 180 days)
//   implied   = max(1, round(base x momentum x tenure))
//
// Why these three pieces: TVL is the value the protocol already secures, so it
// anchors the size of any token; the seven-day change is the freshest momentum the
// snapshot carries, clamped so one wild week cannot double or halve a protocol;
// tenure rewards protocols that have run a long time with no token yet, because a
// long clean record is the best evidence the snapshot gives that the protocol is
// real and its token, if it ever comes, is not a rush job. No protocol name is
// ever special-cased: the same function scores every row, and the board's order is
// the model's order, nothing else.
//
// The board covers every slug in the snapshot's watchlist (the floor, never the
// ceiling) and adds pre-token protocols below the floor, by TVL, that pass the
// same screen the house used for the watchlist: no wrapped, staked or bridged
// product of a token that already trades, no exchange, no versioned pool.
// Protocols whose token already trades are kept apart in the Live view and shown
// at the market's own value, never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
